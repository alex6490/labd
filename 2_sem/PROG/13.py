#Переменные:
            #n - количество элементов множества
            #s - исходное множество
            #el - элемент для добавления в множество
import random as r
n = int(input('Введите количество элементов множества '))
s = set()
for i in range(n):
    el = r.randint(-10, 10)
    s.add(el)
for el in s:
    print(el, end=' ')
