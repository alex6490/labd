            #otr - количество отрицательных элементов
            #cr - среднее всех отрицальных
from random import *
n = int(input('Введите количество элементов списка '))
lst = []
for i in range(n):
    x = randint(-10,10)
    lst.append(x)
otr = 0
s = 0
for i in lst:
    if i < 0:
        otr += 1
        s+=i
if otr >0:
    cr = s/otr
else:
    cr = "не обнаружено, отрицательных элементов нет"
print('Массив =', lst)
print('Среднее всех отрицательных', cr)


