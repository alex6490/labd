#Переменные:
            #lx - список координат x
            #ly - список координат y
            #SCRIPT - логическая переменная для проверки условия
lx = []
ly = []
for i in range(8):
    x = int(input('Введите координату x: '))
    lx.append(x)
for i in range(8):
    y = int(input('Введите координату y: '))
    ly.append(y)
SCRIPT = False
for i in range(8):
    for j in range(i + 1, 8):
        if lx[i] == lx[j] or ly[i] == ly[j] or abs(lx[i] - lx[j]) == abs(ly[i] - ly[j]):
            SCRIPT = True
            break
    if SCRIPT:
        break
if SCRIPT:
    print('YES')
else:
    print('NO')
            