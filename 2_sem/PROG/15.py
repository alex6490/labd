def find_fam(s, fam):
    fl = False
    for i in range(len(s)):
        for j in range(i+1, len(s)):
            if s[i:j] == fam[i:j] and len(s)>=len(fam):
                fl = True
    return fl
#Ввод строки
s = input('Введите строку: ')
#Ввод фамилии
fam = input('Введите фамилию: ')
#Проверка наличия фамилии в строке
#Вывод результата
if find_fam(s, fam):
    print('Фамилия найдена в строке.')
else:
    print('Фамилия не найдена в строке.')
    
   

            
            
        

