#Переменные:
            #FILENAME - имя файла
            #N - количество чисел в последовательности
            #count_neg - счётчик отрицательных чисел
            #y - значение i-го элемента последовательности
import struct
from math import sin, cos, pi
FILENAME = "16.bin"
N = int(input("Введите количество чисел в последовательности: "))
#1. Формирование бинарного файла
#создаём пустой файл
f = open(FILENAME, "wb")  # открываем файл для записи в бинарном режиме
for i in range(1, N + 1):
    if i <= 8:
        y = sin(i * pi / 8)  # для i от 1 до 8
    else:
        y = 4 * cos(i * (pi + 1) / 5)  # для i от 9 до 20
    f.write(struct.pack("f", y))
f.close()  # закрываем файл
#2. Чтение, подсчёт отрицательных и вывод
count_neg = 0
print(f"Содержимое файла {FILENAME}:")
f = open(FILENAME, "rb")  # открываем файл для чтения в бинарном режиме
s = f.read(4)  # читаем первые 4 байта
i = 0
while s:
    f.seek(i * 4)  # перемещаемся к i-му числу (4 байта на число)
    data = f.read(4)  # читаем 4 байта
    y = struct.unpack("f", data)[0]  # преобразуем байты в число
    print(f"y[{i + 1}] = {y:.6f}")
    if y < 0:
        count_neg += 1  # увеличиваем счётчик отрицательных чисел
    s = f.read(4)  # читаем следующие 4 байта
    i += 1
f.close()
print(f"\nКоличество отрицательных чисел: {count_neg}")


