#Переменные:
            #n - количество элементов кортежа
            #k - исходный кортеж
            #el - элемент для поиска в кортеже
            #ril - число для проверки, является ли оно произведением двух элементов кортежа
import random as r
n = int(input('Введите количество элементов кортежа '))
k = tuple()
for i in range(n):
    el = r.randint(-10, 10)
    k += (el,)
print('Кортеж:', k)
ril = int(input('Введите число для поиска в кортеже '))
for i in range(n):
    for j in range(i+1, n):
        if ril == k[i]*k[j]:
            print(f'Число {ril} является произведением элементов кортежа с индексами {i} и {j}')
    