#Переменные:
            #n - количество элементов кортежа
            #k - исходный кортеж
            #x - элемент для удаления
n = int(input("Введите n:"))
k = tuple(int(input("Введите число:")) for _ in range(n))
x = int(input("Введите элемент x:"))
i = 0
while i <len(k) and k[i] != x: # 1 2 3 4 5
    i += 1
if i == len(k):
    print(k)
else:
    print(k[:i]+k[i+1:])