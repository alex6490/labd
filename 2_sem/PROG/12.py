            #n - количество элементов списков
n = int(input('Введите количество элементов списков '))
l1 = []
l2 = []
d = {}
for i in range(n):
    el1 = input('Введите элемент первого списка ')
    el2 = input('Введите элемент второго списка ')
    l1.append(el1)
    l2.append(el2)
for i in range(n):
    d[l1[i]] = l2[i]
print(d)
            