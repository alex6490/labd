def print_table(data):
    #вывод красивой таблицы
    if len(data) == 0:
        print("База данных пуста.")
        return

    table = PrettyTable()

    table.field_names = [
        "№",
        "ФИО",
        "100 м (сек)",
        "1 км (сек)",
        "Прыжок в длину (м)",
        "Прыжок в высоту (м)"
    ]

    number = 1

    for row in data:
        table.add_row([
            number,
            row["fio"],
            format_num(row["100m"]),
            format_num(row["1km"]),
            format_num(row["long_jump"]),
            format_num(row["high_jump"])
        ])

        number += 1

    print(table)